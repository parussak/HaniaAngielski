import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const modules = JSON.parse(readFileSync(new URL('../../src/data/modules.json', import.meta.url),'utf8'));
const data = modules[0];
test('pełna nauka, błędy, wznowienie, eksport i odtworzenie na innym urządzeniu', async ({ page, browser }) => {
  const errors: string[] = []; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Cześć, Haniu'})).toBeVisible();
  await page.screenshot({path:'test-results/home-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Otwórz moduł Mój mały świat'}).click();
  await page.getByRole('button',{name:/^Gramatyka/}).click();
  await page.getByText('Wpisuję odpowiedź',{exact:true}).click();
  await page.getByRole('button',{name:/Rozpocznij naukę/}).click();
  const prompt = await page.locator('.question').innerText();
  const q = data.exercises.find((q:any)=>q.prompt===prompt);
  await page.getByRole('textbox').fill('wrong');
  await page.getByRole('button',{name:/Sprawdź/}).click();
  await expect(page.getByText('Spokojnie, tak właśnie się uczymy.')).toBeVisible();
  await page.reload();
  await page.getByRole('button',{name:'Kontynuuj',exact:true}).click();
  await expect(page.getByText('Spokojnie, tak właśnie się uczymy.')).toBeVisible();
  await page.getByRole('button',{name:'Spróbuję jeszcze raz'}).click();
  await page.getByRole('textbox').fill(q.answers[0]);
  await page.getByRole('button',{name:/Sprawdź/}).click();
  await page.getByRole('button',{name:'Dalej',exact:false}).click();
  await expect(page.locator('#app')).toHaveAttribute('aria-busy','false');
  for(let i=0;i<6;i++) {
    if(await page.getByRole('heading',{name:'Dobra robota, Haniu!'}).isVisible()) break;
    const text = await page.locator('.question').innerText();
    const exercise=data.exercises.find((q:any)=>q.prompt===text);
    await page.getByRole('textbox').fill(exercise.answers[0]);
    await page.getByRole('button',{name:/Sprawdź/}).click();
    await page.getByRole('button',{name:'Dalej',exact:false}).click();
    await expect(page.locator('#app')).toHaveAttribute('aria-busy','false');
  }
  await expect(page.getByRole('heading',{name:'Dobra robota, Haniu!'})).toBeVisible();
  await expect(page.locator('.summary-score')).toContainText('3 / 4');
  await page.getByRole('button',{name:'Moja nauka',exact:true}).click();
  await page.getByRole('button',{name:'Otwórz moduł Mój mały świat'}).click();
  await page.getByRole('button',{name:/^Fiszki/}).click();
  await page.getByRole('button',{name:/Rozpocznij naukę/}).click();
  await page.getByRole('button',{name:'Pokaż odpowiedź'}).click();
  const revealed = await page.locator('.flash-answer').innerText();
  await page.reload(); await page.getByRole('button',{name:'Kontynuuj',exact:true}).click();
  await expect(page.locator('.flash-answer')).toHaveText(revealed);
  await page.getByRole('button',{name:'Kopia postępów',exact:true}).click();
  const downloaded=page.waitForEvent('download');
  await page.getByRole('button',{name:'Zapisz kopię postępów',exact:true}).click();
  const download=await downloaded; const path=(await download.path())!;
  const original=JSON.parse(readFileSync(path,'utf8'));
  expect(original.progress.sessions).toHaveLength(1);
  expect(original.progress.active.phase).toBe('revealed');
  // Druga karta nie może równocześnie nadpisać wyników.
  const duplicate=await page.context().newPage(); await duplicate.goto('/');
  await expect(duplicate.getByRole('heading',{name:'Nauka jest otwarta w innej karcie'})).toBeVisible(); await duplicate.close();
  const context=await browser.newContext({viewport:{width:390,height:844}});
  const mobile=await context.newPage(); await mobile.goto('/');
  await expect(mobile.getByRole('heading',{name:'Cześć, Haniu'})).toBeVisible();
  expect(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await mobile.screenshot({path:'test-results/home-mobile.png',fullPage:true});
  await mobile.getByRole('button',{name:'Kopia postępów',exact:true}).click();
  await mobile.locator('#import-file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{oops')});
  await expect(mobile.getByRole('status')).toContainText('Nie można odczytać');
  await mobile.locator('#import-file').setInputFiles(path);
  await mobile.getByRole('button',{name:'Anuluj',exact:true}).click();
  await mobile.getByRole('button',{name:'Moje postępy',exact:true}).click();
  await expect(mobile.getByText('Tu wyrosną Twoje postępy')).toBeVisible();
  await mobile.getByRole('button',{name:'Kopia postępów',exact:true}).click();
  await mobile.locator('#import-file').setInputFiles(path);
  await mobile.getByRole('button',{name:'Zastąp postępy',exact:true}).click();
  await expect(mobile.getByRole('status')).toContainText('Kopia została wczytana');
  await mobile.reload();
  await mobile.getByRole('button',{name:'Kontynuuj',exact:true}).click();
  await expect(mobile.locator('.flash-answer')).toHaveText(revealed);
  await mobile.getByRole('button',{name:'Znam to',exact:false}).click();
  await mobile.getByRole('button',{name:'Moje postępy',exact:true}).click();
  await expect(mobile.locator('.history-score')).toContainText('3/4');
  expect(errors).toEqual([]); await context.close();
});
test('nieudany zapis nie udaje sukcesu i nie zmienia poprzednich wyników',async({page})=>{
  await page.goto('/'); await page.getByRole('button',{name:'Otwórz moduł Mój mały świat'}).click();
  await page.getByRole('button',{name:/Rozpocznij naukę/}).click();
  await page.evaluate(()=>{IDBObjectStore.prototype.put=function(){throw new DOMException('Full','QuotaExceededError');};});
  await page.getByRole('button',{name:'Pokaż odpowiedź'}).click();
  await expect(page.getByRole('alert')).toContainText('Nie udało się zapisać zmiany');
  await expect(page.getByRole('button',{name:'Pokaż odpowiedź'})).toBeVisible();
  await page.reload(); await page.getByRole('button',{name:'Kontynuuj',exact:true}).click();
  await expect(page.getByRole('button',{name:'Pokaż odpowiedź'})).toBeVisible();
});
